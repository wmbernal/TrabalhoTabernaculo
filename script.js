const menuToggle = document.querySelector(".menu-toggle");
const siteNav = document.querySelector(".site-nav");
const readingProgress = document.querySelector(".reading-progress");
const languageSelect = document.querySelector(".language-select");

if (menuToggle && siteNav) {
  menuToggle.addEventListener("click", () => {
    const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-expanded", String(!isExpanded));
    siteNav.classList.toggle("is-open", !isExpanded);
  });

  siteNav.addEventListener("click", (event) => {
    if (event.target instanceof HTMLAnchorElement) {
      menuToggle.setAttribute("aria-expanded", "false");
      siteNav.classList.remove("is-open");
    }
  });
}

function setLanguage(language) {
  const translation = translations[language];
  if (!translation) {
    return;
  }

  const page = translation.pages[document.body.dataset.page];
  document.documentElement.lang = language === "pt" ? "pt-BR" : language;
  document.title = `${page.sectionTitle} | ${translation.projectLabel}`;
  document.querySelector('meta[name="description"]').content = page.description;
  document.querySelector(".brand").href = "index.html";
  document.querySelectorAll(".site-nav a").forEach((link, index) => {
    link.href = `pagina-${index + 1}.html`;
  });

  document.querySelectorAll("[data-copy]").forEach((element) => {
    const key = element.dataset.copy;
    if (translation[key]) {
      element.textContent = translation[key];
    } else if (page[key]) {
      element.textContent = page[key];
    }
  });

  const articleBody = document.querySelector(".article-body");
  articleBody.replaceChildren();

  if (page.sections) {
    const intro = document.createElement("p");
    intro.textContent = page.intro;
    articleBody.append(intro);

    page.sections.forEach((section) => {
      const paragraph = document.createElement("p");
      const title = document.createElement("strong");
      title.textContent = section.title;
      paragraph.append(title, ` ${section.text}`);
      articleBody.append(paragraph);
    });
  } else {
    page.paragraphs.forEach((text) => {
      const paragraph = document.createElement("p");
      paragraph.textContent = text;
      articleBody.append(paragraph);
    });
  }

  document.querySelector(".skip-link").textContent = translation.skipLink;
  document.querySelector(".site-nav").setAttribute("aria-label", translation.navLabel);
  document.querySelector(".brand").setAttribute("aria-label", translation.homeLinkLabel);
  document.querySelector(".page-aside").setAttribute("aria-label", translation.asideRegionLabel);
  document.querySelector(".page-progress").setAttribute(
    "aria-label",
    translation.progressLabel.replace("{current}", document.body.dataset.page)
  );
  document.querySelector(".language-picker span").textContent = translation.languageLabel;
  languageSelect.setAttribute("aria-label", translation.languageLabel);
  languageSelect.value = language;

  updateLanguageLinks(language);

  const currentUrl = new URL(window.location.href);
  if (language === "pt") {
    currentUrl.searchParams.delete("lang");
  } else {
    currentUrl.searchParams.set("lang", language);
  }
  if (currentUrl.href !== window.location.href) {
    window.history.replaceState(null, "", currentUrl.href);
  }
}

function updateLanguageLinks(language) {
  document.querySelectorAll("a[href]").forEach((link) => {
    const href = link.getAttribute("href");
    if (!/\.html(?:[?#]|$)/i.test(href)) {
      return;
    }

    const url = new URL(href, window.location.href);
    if (language === "pt") {
      url.searchParams.delete("lang");
    } else {
      url.searchParams.set("lang", language);
    }
    link.href = url.href;
  });
}

function setHomeLanguage(language) {
  const copy = homeTranslations[language];
  if (!copy) {
    return;
  }

  document.documentElement.lang = language === "pt" ? "pt-BR" : language;
  document.title = copy.homeTitle;
  document.querySelector('meta[name="description"]').content = copy.homeDescription;
  document.querySelectorAll("[data-home-copy]").forEach((element) => {
    const key = element.dataset.homeCopy;
    if (copy[key]) {
      element.textContent = copy[key];
    }
  });
  document.querySelectorAll("[data-home-alt]").forEach((image) => {
    image.alt = copy[image.dataset.homeAlt];
  });
  document.querySelector(".skip-link").textContent = copy.skipLink;
  document.querySelector(".brand").setAttribute("aria-label", copy.homeLinkLabel);
  document.querySelector(".home-nav").setAttribute("aria-label", copy.navLabel);
  document.querySelector(".language-picker span").textContent = copy.languageLabel;
  document.querySelector(".language-select").setAttribute("aria-label", copy.languageLabel);
  document.querySelector(".carousel").setAttribute("aria-label", copy.carouselLabel);
  document.querySelector(".carousel-dots").setAttribute("aria-label", copy.carouselChoices);
  document.querySelector("[data-carousel-prev]").setAttribute("aria-label", copy.carouselPrevious);
  document.querySelector("[data-carousel-next]").setAttribute("aria-label", copy.carouselNext);
  document.querySelectorAll(".carousel-dot").forEach((dot, index) => {
    dot.setAttribute("aria-label", `${copy.carouselChoices}: ${index + 1} / 3`);
  });
  document.querySelectorAll(".chapter-card").forEach((link, index) => {
    link.href = `pagina-${index + 1}.html`;
  });
  updateLanguageLinks(language);

  const currentUrl = new URL(window.location.href);
  if (language === "pt") {
    currentUrl.searchParams.delete("lang");
  } else {
    currentUrl.searchParams.set("lang", language);
  }
  if (currentUrl.href !== window.location.href) {
    window.history.replaceState(null, "", currentUrl.href);
  }

}

if (languageSelect) {
  const requestedLanguage = new URLSearchParams(window.location.search).get("lang");
  const availableLanguages = document.body.dataset.home === "true" ? homeTranslations : translations;
  const initialLanguage = Object.hasOwn(availableLanguages, requestedLanguage) ? requestedLanguage : "pt";
  const applyLanguage = document.body.dataset.home === "true" ? setHomeLanguage : setLanguage;
  applyLanguage(initialLanguage);
  languageSelect.addEventListener("change", () => applyLanguage(languageSelect.value));
}

let activeSlide = 0;
const slides = Array.from(document.querySelectorAll(".carousel-slide"));
const carouselDots = Array.from(document.querySelectorAll(".carousel-dot"));

function showSlide(index) {
  if (slides.length === 0) {
    return;
  }

  activeSlide = (index + slides.length) % slides.length;
  slides.forEach((slide, slideIndex) => {
    const isActive = slideIndex === activeSlide;
    slide.classList.toggle("is-active", isActive);
    slide.setAttribute("aria-hidden", String(!isActive));
    slide.inert = !isActive;
  });
  carouselDots.forEach((dot, dotIndex) => {
    const isActive = dotIndex === activeSlide;
    dot.classList.toggle("is-active", isActive);
    dot.setAttribute("aria-pressed", String(isActive));
  });
}

if (slides.length > 0) {
  document.querySelector("[data-carousel-prev]").addEventListener("click", () => showSlide(activeSlide - 1));
  document.querySelector("[data-carousel-next]").addEventListener("click", () => showSlide(activeSlide + 1));
  carouselDots.forEach((dot) => {
    dot.addEventListener("click", () => showSlide(Number(dot.dataset.goTo)));
  });
}

if (readingProgress) {
  const updateReadingProgress = () => {
    const scrollableHeight = document.documentElement.scrollHeight - window.innerHeight;
    const progress = scrollableHeight > 0 ? (window.scrollY / scrollableHeight) * 100 : 0;
    readingProgress.style.width = `${Math.min(progress, 100)}%`;
  };

  window.addEventListener("scroll", updateReadingProgress, { passive: true });
  window.addEventListener("resize", updateReadingProgress);
  updateReadingProgress();
}
